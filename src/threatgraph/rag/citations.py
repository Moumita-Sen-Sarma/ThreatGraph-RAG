from __future__ import annotations

import re


class CitationValidator:
    """
    Validate citations generated by the LLM.

    Supported citation format:

        [G1]
        [G2]
        [V1]
        [V2]
    """

    CITATION_PATTERN = re.compile(
        r"\[(G\d+|V\d+)\]"
    )

    def extract_citations(
        self,
        answer: str,
    ) -> list[str]:
        """
        Extract all graph/vector evidence IDs
        mentioned in the answer.
        """

        return self.CITATION_PATTERN.findall(
            answer
        )

    def validate(
        self,
        answer: str,
        graph_evidence: list[dict],
        vector_evidence: list[dict],
    ) -> dict:
        """
        Check whether every citation in the answer
        refers to evidence that actually exists.
        """

        used_citations = (
            self.extract_citations(answer)
        )

        valid_ids = {
            item["evidence_id"]
            for item in graph_evidence
        }

        valid_ids.update(
            item["evidence_id"]
            for item in vector_evidence
        )

        invalid_citations = [
            citation
            for citation in used_citations
            if citation not in valid_ids
        ]

        valid_citations = [
            citation
            for citation in used_citations
            if citation in valid_ids
        ]

        return {
            "used_citations": used_citations,
            "valid_citations": valid_citations,
            "invalid_citations": invalid_citations,
            "all_citations_valid": (
                len(invalid_citations) == 0
            ),
        }